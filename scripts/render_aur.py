"""Render the AUR PKGBUILD and .SRCINFO for one release.

    python3 scripts/render_aur.py --version 0.8.0 --sha256 <hex> --out aur

The sha256 is of GitHub's tag tarball. .SRCINFO is written here because the Ubuntu release runner has no makepkg;
`tests/test_render_aur.py` holds the two files to the same fields.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

NAME = "deskpilot"
DESCRIPTION = "Desktop control for agents on Hyprland: click and type in a window while the user keeps working"
URL = "https://github.com/agent-labs-dev/deskpilot"
# The plugin is compiled on the user's machine for the Hyprland it loads into, so the compiler and the libraries
# its Makefile asks pkg-config for are needed at run time, not only to build the package.
DEPENDS = (
    "python",
    "python-evdev",
    "python-jeepney",
    "python-pillow",
    "python-mcp",
    "python-pydantic",
    "hyprland",
    "grim",
    "gcc",
    "make",
    "pkgconf",
    "pixman",
    "libdrm",
    "libxcb",
    "libxkbcommon",
    "cairo",
)
MAKEDEPENDS = ("python-build", "python-installer", "python-hatchling")
OPTDEPENDS = (
    "wl-clipboard: read and set the clipboard",
    "ffmpeg: record a window or a recipe to an mp4",
    "at-spi2-core: target elements through the accessibility tree",
)


def _quoted(items: tuple[str, ...]) -> str:
    return " ".join(f"'{item}'" for item in items)


def pkgbuild(version: str, sha256: str) -> str:
    return f"""# Maintainer: cjber <cjberragan at gmail dot com>
# Generated by {URL}/blob/main/scripts/render_aur.py; edits are overwritten on the next release.
pkgname={NAME}
pkgver={version}
pkgrel=1
pkgdesc="{DESCRIPTION}"
arch=('any')
url="{URL}"
license=('MIT')
depends=({_quoted(DEPENDS)})
makedepends=({_quoted(MAKEDEPENDS)})
optdepends=({_quoted(OPTDEPENDS)})
source=("${{pkgname}}-${{pkgver}}.tar.gz::{URL}/archive/refs/tags/v${{pkgver}}.tar.gz")
sha256sums=('{sha256}')

build() {{
  cd "${{pkgname}}-${{pkgver}}"
  python -m build --wheel --no-isolation
}}

package() {{
  cd "${{pkgname}}-${{pkgver}}"
  python -m installer --destdir="${{pkgdir}}" dist/*.whl
  install -Dm644 LICENSE "${{pkgdir}}/usr/share/licenses/${{pkgname}}/LICENSE"
  install -Dm644 README.md "${{pkgdir}}/usr/share/doc/${{pkgname}}/README.md"
  cp -a docs skills "${{pkgdir}}/usr/share/doc/${{pkgname}}/"
}}
"""


def srcinfo(version: str, sha256: str) -> str:
    lines = [
        f"pkgbase = {NAME}",
        f"\tpkgdesc = {DESCRIPTION}",
        f"\tpkgver = {version}",
        "\tpkgrel = 1",
        f"\turl = {URL}",
        "\tarch = any",
        "\tlicense = MIT",
        *(f"\tmakedepends = {item}" for item in MAKEDEPENDS),
        *(f"\tdepends = {item}" for item in DEPENDS),
        *(f"\toptdepends = {item}" for item in OPTDEPENDS),
        f"\tsource = {NAME}-{version}.tar.gz::{URL}/archive/refs/tags/v{version}.tar.gz",
        f"\tsha256sums = {sha256}",
        "",
        f"pkgname = {NAME}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", required=True)
    parser.add_argument("--sha256", required=True)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    if not re.fullmatch(r"\d+\.\d+\.\d+", args.version):
        parser.error(f"--version {args.version!r} is not X.Y.Z")
    if not re.fullmatch(r"[0-9a-f]{64}", args.sha256):
        parser.error("--sha256 is not 64 hex characters")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "PKGBUILD").write_text(pkgbuild(args.version, args.sha256))
    (args.out / ".SRCINFO").write_text(srcinfo(args.version, args.sha256))


if __name__ == "__main__":
    main()
